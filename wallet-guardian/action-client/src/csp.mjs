/**
 * WALLET-CONNECT-01 W-B5: Content-Security-Policy for the static client (Cloudflare Pages _headers).
 * Single source of truth used by vite.config.ts (emits dist/_headers) and the tests.
 *
 * Base (every build): only same-origin scripts/styles/API, data: images (EIP-6963 icons, favicon),
 * the trusted BSC RPC used for read-only re-checks. No inline script, no eval, no framing.
 * WalletConnect builds add exactly what the pinned SDK uses (see walletconnect-config.mjs):
 * the relay WebSocket and the Verify iframe. No wildcards.
 */
import { TRUSTED_LISTA } from "./trusted-lista.mjs";

const RELAY = "wss://relay.walletconnect.org";
const VERIFY = "https://verify.walletconnect.org";

/** @param {{ walletConnect?: boolean }} [options] */
export function cspDirectives({ walletConnect = false } = {}) {
  const rpcOrigin = new URL(TRUSTED_LISTA.rpcUrl).origin;
  return [
    ["default-src", ["'none'"]],
    ["script-src", ["'self'"]],
    ["style-src", ["'self'"]],
    ["img-src", ["'self'", "data:"]],
    ["connect-src", ["'self'", rpcOrigin, ...(walletConnect ? [RELAY] : [])]],
    ["frame-src", walletConnect ? [VERIFY] : ["'none'"]],
    ["manifest-src", ["'self'"]],
    ["base-uri", ["'none'"]],
    ["form-action", ["'none'"]],
    ["frame-ancestors", ["'none'"]],
    ["object-src", ["'none'"]],
  ];
}

export function contentSecurityPolicy(options) {
  return cspDirectives(options).map(([name, values]) => `${name} ${values.join(" ")}`).join("; ");
}

/** Full _headers file for the static client. Pages Function responses are not covered by it. */
export function pagesHeaders(options) {
  return [
    "# Static client shell only. This file does not apply to Pages Function responses.",
    "# Generated by vite.config.ts from src/csp.mjs. WalletConnect: " + (options?.walletConnect ? "enabled" : "disabled") + ".",
    "/*",
    "  Referrer-Policy: no-referrer",
    "  X-Content-Type-Options: nosniff",
    "  X-Frame-Options: DENY",
    `  Content-Security-Policy: ${contentSecurityPolicy(options)}`,
    "",
  ].join("\n");
}
